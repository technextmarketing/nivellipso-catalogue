  function renderToc(filter = '') {
    const f = fold(filter.trim());
    const hit = s => !f || fold(s).includes(f);
    const mark = s => {
      if (!f) return esc(s);
      const i = fold(s).indexOf(f);
      return i < 0 ? esc(s) : esc(s.slice(0, i)) + '<mark>' + esc(s.slice(i, i + f.length)) + '</mark>' + esc(s.slice(i + f.length));
    };
    const row = (label, page, no = '') => `<button class="toc__ch" type="button" data-go="${page}"><span class="toc__no">${no}</span><span class="toc__title">${mark(label)}</span><span class="toc__pg">${page}</span></button>`;
    let html = '';
    const front = [['Cover', 1], ['Table of contents', 3]].filter(([l]) => hit(l));
    if (front.length) html += `<li class="toc__group toc__group--front">${front.map(([l, p]) => row(l, p)).join('')}</li>`;
    let count = front.length;
    for (const c of S.chapters) {
      const chHit = hit(c.title) || hit(c.no);
      const secs = c.sections.filter(s => chHit || hit(s.title));
      if (!chHit && !secs.length) continue;
      count++;
      html += `<li class="toc__group${f ? ' open' : ''}" data-ch="${c.no}"><button class="toc__ch" type="button" data-go="${c.page}" data-ch="${c.no}"><span class="toc__no">${c.no}</span><span class="toc__title">${mark(c.title)}</span><span class="toc__pg">${c.page}</span></button>
        <ol class="toc__secs">${secs.map(s => `<li><button class="toc__sec" type="button" data-go="${s.page}" data-sec="${s.page}"><span>${mark(s.title)}</span><span class="toc__pg">${s.page}</span></button></li>`).join('')}</ol></li>`;
    }
    if (hit('Back cover')) { html += `<li class="toc__group toc__group--front">${row('Back cover', S.N)}</li>`; count++; }
    el.toc.innerHTML = count ? html : `<li class="toc__empty">Nothing in the contents matches “${esc(filter)}”. <button class="btn--quiet btn" type="button" data-searchfor="${esc(filter)}">Search all pages</button></li>`;
    tocCurrent(!f);
  }
