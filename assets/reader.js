  // ------------------------------------------------------------------ search model
  function parseQuery(raw) {
    const q = raw.trim();
    if (!q) return null;
    const c = compact(q);
    const tokens = fold(q).split(/\s+/).filter(Boolean);
    const partLike = /\d/.test(c) && c.length >= 3 && /^[a-z0-9]+$/.test(c) && !tokens.some(t => /^[a-z]{4,}$/.test(t));
    if (partLike) {
      const SEP = '[\\s\\-–—./·]*';
      return { mode: 'part', c, res: [new RegExp(c.split('').map(escRe).join(SEP), 'g')] };
    }
    const terms = tokens.filter(t => t.length >= 2 || /\d/.test(t));
    if (!terms.length) return null;
    return { mode: 'terms', terms, res: terms.map(t => new RegExp(escRe(t), 'g')) };
  }

  function findAll(re, s, limit = 400) {
    const out = []; re.lastIndex = 0; let m;
    while ((m = re.exec(s)) && out.length < limit) { if (!m[0].length) { re.lastIndex++; continue; } out.push([m.index, m.index + m[0].length]); }
    return out;
  }

  function matchBoxes(d, qi) {
    const boxes = [];
    for (const re of qi.res) {
      for (const [a, b] of findAll(re, d.joined)) {
        const byRun = new Map();
        for (let i = a; i < b; i++) {
          const m = d.map[i]; if (!m) continue;
          const e = byRun.get(m[0]) || [m[1], m[1]];
          e[0] = Math.min(e[0], m[1]); e[1] = Math.max(e[1], m[1]);
          byRun.set(m[0], e);
        }
        byRun.forEach(([k0, k1], ri) => {
          const r = d.w[ri];
          boxes.push([r.x + r.cx[k0], r.y, r.cx[k1 + 1] - r.cx[k0], r.h]);
        });
      }
    }
    return boxes;
  }

